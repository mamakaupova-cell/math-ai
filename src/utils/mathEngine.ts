// Fraction helper for exact rational arithmetic
export class Fraction {
  num: number;
  den: number;

  constructor(num: number, den: number = 1) {
    if (den === 0) throw new Error("Бөлімі нөлге тең бола алмайды");
    const sign = (num < 0 ? -1 : 1) * (den < 0 ? -1 : 1);
    const n = Math.abs(num);
    const d = Math.abs(den);
    const g = Fraction.gcd(n, d);
    this.num = sign * (n / g);
    this.den = d / g;
  }

  static gcd(a: number, b: number): number {
    a = Math.abs(a);
    b = Math.abs(b);
    while (b) {
      const t = b;
      b = a % b;
      a = t;
    }
    return a || 1;
  }

  multiply(other: Fraction): Fraction {
    return new Fraction(this.num * other.num, this.den * other.den);
  }

  divide(other: Fraction): Fraction {
    return new Fraction(this.num * other.den, this.den * other.num);
  }

  add(other: Fraction): Fraction {
    return new Fraction(this.num * other.den + other.num * this.den, this.den * other.den);
  }

  subtract(other: Fraction): Fraction {
    return new Fraction(this.num * other.den - other.num * this.den, this.den * other.den);
  }

  toString(): string {
    if (this.den === 1) return `${this.num}`;
    return `${this.num}/${this.den}`;
  }

  toLatex(): string {
    if (this.den === 1) return `${this.num}`;
    const sign = this.num < 0 ? '-' : '';
    return `${sign}\\frac{${Math.abs(this.num)}}{${this.den}}`;
  }
}

/**
 * Verifies that a rational multiplication problem expression evaluates to the given answer.
 */
export function verifyRationalMultiplication(a: number, b: number, expected: number): boolean {
  const actual = Math.round(a * b * 10000) / 10000;
  const exp = Math.round(expected * 10000) / 10000;
  return Math.abs(actual - exp) < 0.0001;
}

