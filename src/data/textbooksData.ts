export function getTextbooksForGradeAndSubject(
  grade: number,
  subject: string,
  publisherName?: string
): TextbookCatalogItem[] {
  return TEXTBOOKS_CATALOG.filter(tb => {
    if (tb.grade !== grade) return false;
    if (tb.subject !== subject) return false;
    if (publisherName && publisherName !== 'all' && tb.publisher !== publisherName) return false;
    return true;
  });
}
